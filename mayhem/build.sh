#!/usr/bin/env bash
#
# mayhem/build.sh — build the quake3e fuzz harnesses (sanitized + standalone) and the known-answer
# self-test used by mayhem/test.sh. Quake3e has no library target, so the parser modules the
# harnesses exercise are compiled straight from the engine tree (upstream files untouched).
set -euo pipefail

# clang rejects SOURCE_DATE_EPOCH='' (empty) — it must be unset or a valid integer.
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

SRC="${SRC:-/mayhem}"
cd "$SRC"

# engine modules under test + the host stand-ins (mayhem/harnesses/q3_stubs.c)
ENGINE_SRCS=(
  code/qcommon/q_shared.c
  code/qcommon/q_math.c
  code/qcommon/msg.c
  code/qcommon/huffman_static.c
  code/qcommon/puff.c
  code/renderercommon/tr_image_png.c
  code/renderercommon/tr_image_pcx.c
  code/botlib/l_script.c
  code/botlib/l_precomp.c
  code/botlib/l_memory.c
  code/botlib/l_libvar.c
  code/botlib/be_aas_file.c
  mayhem/harnesses/q3_stubs.c
)
TARGETS=(fuzz_png fuzz_pcx fuzz_inflate fuzz_script fuzz_precomp fuzz_aas fuzz_msg)

# build/ is gitignored upstream; every file here is regenerated by this script
FUZZ_OBJ=build/mayhem-fuzz
TEST_OBJ=build/mayhem-test
mkdir -p "$FUZZ_OBJ" "$TEST_OBJ"

objname() { echo "$1" | tr '/' '_' | sed 's/\.c$/.o/'; }

# 1) the fuzzed code, instrumented: sanitizers + coverage (fuzzer-no-link) + DWARF 3
# UBSan relaxed on the engine objects for three benign-on-x86 patterns that fire on nearly every
# mutated input and would halt the run before it reaches memory bugs: unaligned uint32 loads
# (huffman_static.c), `byte << 24` in LongSwap (q_shared.c), float->unsigned long casts (l_script.c).
# ASan and every other UBSan check stay halting.
RELAX="-fno-sanitize=alignment,shift-base,float-cast-overflow"
FUZZ_CFLAGS="-O1 $SANITIZER_FLAGS $RELAX -fsanitize=fuzzer-no-link $DEBUG_FLAGS -DDEDICATED -DBOTLIB -w"
pids=()
for s in "${ENGINE_SRCS[@]}"; do
  $CC $FUZZ_CFLAGS -c "$s" -o "$FUZZ_OBJ/$(objname "$s")" &
  pids+=($!)
done
for p in "${pids[@]}"; do wait "$p"; done

$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c mayhem/lsan_off.cc -o "$FUZZ_OBJ/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$FUZZ_OBJ/standalone_main.o"

ENGINE_OBJS=()
for s in "${ENGINE_SRCS[@]}"; do ENGINE_OBJS+=("$FUZZ_OBJ/$(objname "$s")"); done

# 2) each harness twice: libFuzzer binary and run-once standalone reproducer
for t in "${TARGETS[@]}"; do
  $CC -O1 $SANITIZER_FLAGS $DEBUG_FLAGS -w -c "mayhem/harnesses/$t.c" -o "$FUZZ_OBJ/$t.o"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE \
      "$FUZZ_OBJ/$t.o" "${ENGINE_OBJS[@]}" "$FUZZ_OBJ/lsan_off.o" -lm -o "/mayhem/$t"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS \
      "$FUZZ_OBJ/$t.o" "$FUZZ_OBJ/standalone_main.o" "${ENGINE_OBJS[@]}" "$FUZZ_OBJ/lsan_off.o" -lm \
      -o "/mayhem/$t-standalone"
done

# 3) the known-answer self-test, normal flags, no sanitizers (test.sh only runs it)
TEST_CFLAGS="-O2 $COVERAGE_FLAGS -DDEDICATED -DBOTLIB -w"
for s in "${ENGINE_SRCS[@]}" mayhem/selftest/selftest.c; do
  $CC $TEST_CFLAGS -c "$s" -o "$TEST_OBJ/$(objname "$s")"
done
$CC $COVERAGE_FLAGS "$TEST_OBJ"/*.o -lm -o /mayhem/quake3e_selftest
