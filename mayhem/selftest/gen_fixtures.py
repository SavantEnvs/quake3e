#!/usr/bin/env python3
"""Regenerates selftest/fixtures.h (known-answer inputs) and the starter seeds under mayhem/<target>/testsuite/.

Not run by the build; the outputs are committed.
"""
import os
import struct
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def chunk(tag, body):
    return struct.pack(">I", len(body)) + tag + body + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)


def png(w, h, ctype, rows):
    raw = b"".join(b"\x00" + r for r in rows)
    ihdr = struct.pack(">IIBBBBB", w, h, 8, ctype, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def pcx(w, h, pixels, palette):
    hdr = bytearray(128)
    hdr[0], hdr[1], hdr[2], hdr[3] = 10, 5, 1, 8
    struct.pack_into("<HHHH", hdr, 4, 0, 0, w - 1, h - 1)
    hdr[65] = 1
    struct.pack_into("<H", hdr, 66, w)
    body = bytearray()
    for p in pixels:
        body += bytes([0xC1, p]) if p >= 0xC0 else bytes([p])
    pal = bytearray(768)
    for i, rgb in palette.items():
        pal[i * 3:i * 3 + 3] = bytes(rgb)
    return bytes(hdr) + bytes(body) + b"\x0c" + bytes(pal)


def aas():
    f = lambda *v: struct.pack("<%df" % len(v), *v)
    i = lambda *v: struct.pack("<%di" % len(v), *v)
    lumps = [
        i(2, 0) + f(-15, -15, -24, 15, 15, 32),                       # bboxes
        f(0, 0, 0) + f(1, 0, 0) + f(1, 1, 0) + f(0, 1, 0),            # vertexes
        f(0, 0, 1, 0) + i(2),                                         # planes
        i(0, 0, 0, 1, 1, 2, 2, 3, 3, 0),                              # edges
        i(1, 2, 3, 4),                                                # edgeindex
        i(0, 0, 0, 0, 0, 0) + i(0, 0, 4, 0, 1, 0),                    # faces
        i(1),                                                         # faceindex
        i(0, 0, 0) + f(0, 0, 0, 0, 0, 0, 0, 0, 0) + i(1, 1, 0) + f(0, 0, 0, 1, 1, 0, .5, .5, 0),  # areas
        i(0, 0, 0, 0, 0, 0, 0) + i(1, 0, 3, 1, 0, 1, 0),              # areasettings
        i(1, 1, 1) + f(0, 0, 0, 1, 1, 0) + i(1) + struct.pack("<Hxx", 10),  # reachability
        i(0, 0, 0) + i(0, -1, 0),                                     # nodes
        i(0, 0, 0, 0, 0),                                             # portals
        i(0),                                                         # portalindex
        i(0, 0, 0, 0) + i(1, 1, 0, 0),                                # clusters
    ]
    hdr = bytearray(struct.pack("<iii", 0x53414145, 4, 0))
    off = 124
    for l in lumps:
        hdr += struct.pack("<ii", off, len(l))
        off += len(l)
    return bytes(hdr) + b"".join(lumps)


def carray(name, data):
    out = "static const unsigned char %s[] = {" % name
    for n, b in enumerate(data):
        out += ("\n\t" if n % 16 == 0 else " ") + "0x%02x," % b
    return out + "\n};\n"


def main():
    png_rgba = png(2, 2, 6, [bytes([255, 0, 0, 255, 0, 255, 0, 128]), bytes([0, 0, 255, 255, 10, 20, 30, 40])])
    png_rgb = png(3, 2, 2, [bytes(range(0, 9)), bytes(range(100, 109))])
    pcx_img = pcx(2, 2, [0, 1, 2, 0xC1], {0: (1, 2, 3), 1: (10, 20, 30), 2: (100, 110, 120), 0xC1: (7, 8, 9)})
    co = zlib.compressobj(9, zlib.DEFLATED, -15)
    text = b"quake3e quake3e quake3e: the quick brown fox"
    deflated = co.compress(text) + co.flush()
    aas_ok = aas()

    with open(os.path.join(HERE, "fixtures.h"), "w") as fh:
        fh.write("/* generated by gen_fixtures.py */\n")
        fh.write(carray("fx_png_rgba", png_rgba))
        fh.write(carray("fx_png_rgb", png_rgb))
        fh.write(carray("fx_pcx", pcx_img))
        fh.write(carray("fx_deflate", deflated))
        fh.write(carray("fx_aas", aas_ok))

    def seed(target, name, data):
        d = os.path.join(ROOT, target, "testsuite")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, name), "wb") as fh:
            fh.write(data)

    seed("fuzz_png", "rgba_2x2.png", png_rgba)
    seed("fuzz_png", "rgb_3x2.png", png_rgb)
    seed("fuzz_pcx", "paletted_2x2.pcx", pcx_img)
    seed("fuzz_inflate", "text.bin", struct.pack("<H", 255) + deflated)
    seed("fuzz_aas", "minimal.aas", aas_ok)
    seed("fuzz_script", "tokens.txt", b"\x00weapon \"railgun\" { damage 100 speed 1.5e2 flags 0x1f 'c' } // c\n/* c */ a<<=b;")
    seed("fuzz_precomp", "macros.c",
         b"#define SQUARE(x) ((x)*(x))\n#define N 4\n#ifdef N\nint a = SQUARE(N);\n#else\nint a;\n#endif\n"
         b"#if (N > 2) && defined(SQUARE)\nok __LINE__ __FILE__\n#endif\n#undef N\n")
    seed("fuzz_msg", "oob.bin", bytes([1]) + bytes([3, 1, 5, 0x68, 0x69, 0, 2, 4, 8, 9, 10, 7]) + b"\x01\x02\x03\x04\x05\x06\x07\x08")
    seed("fuzz_msg", "huff.bin", bytes([0]) + bytes([1, 5, 9, 10, 3, 2, 7]) + bytes(range(1, 40)))


main()
